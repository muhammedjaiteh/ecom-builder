// ─────────────────────────────────────────────────────────────────────────────
// APEX SWITCHBOARD: /shop/[slug]
// 
// This is the Grand Central Station for Sanndikaa storefronts.
// 1. Resolves the merchant slug and fetches raw product data.
// 2. Fetches the strict JSON brand_tokens generated by the AI Creative Director.
// 3. Merges the AI editorial copy with the raw database rows.
// 4. Reads the theme_matrix and routes the data to the correct $50k React Matrix.
//
// The underlying Matrix components remain entirely "data-blind." They render 
// exactly what this Switchboard hands them. No raw data leaks past this file.
// ─────────────────────────────────────────────────────────────────────────────

// --- Raw row types ---
type StoreRow = {
  id: string;
  shop_name: string | null;
  shop_slug: string | null;
  phone: string | null;
  bio: string | null;
  banner_url: string | null;
  logo_url: string | null;
  theme_matrix?: string | null;
};

const STORE_OPTIONAL_COLUMNS = ['theme_matrix'] as const;

type ProductRow = {
  id: string;
  name: string;
  price: number | string | null;
  description: string | null;
  image_url: string | null;
  image_urls: string[] | null;
  ad_hero_image_url: string | null;
  category: string | null;
  stock_quantity: number | null;
  created_at: string | null;
  kicker?: string | null;
  extraction?: string | null;
  details?: string | null;
  eyebrow?: string | null;
};

const STORE_COLUMNS = 'id, shop_name, shop_slug, phone, bio, banner_url, logo_url';
const PRODUCT_BASE_COLUMNS =
  'id, name, price, description, image_url, image_urls, ad_hero_image_url, category, stock_quantity, created_at';

// Strict typing for the AI-curated JSON payload
type BrandTokens = {
  palette_id: string;
  typography_id: string;
  hero_kicker: string;
  provenance_statement: string;
  curation_heading: string;
  material_truth_1: string;
  material_truth_2: string;
  whatsapp_cta_tone: string;
};

// --- Mapping helpers ---

function clean(value: string | null | undefined): string {
  return (value ?? '').trim();
}

function toParagraphs(value: string | null | undefined): string[] {
  return clean(value)
    .split(/\r?\n+/)
    .map((line) => line.trim())
    .filter(Boolean);
}

function toBullets(value: string | null | undefined): string[] {
  return clean(value)
    .split(/\r?\n|\|/)
    .map((line) => line.trim())
    .filter(Boolean);
}

function pickImage(row: ProductRow): string {
  return (
    clean(row.image_url) ||
    clean(row.image_urls?.find((url) => clean(url))) ||
    clean(row.ad_hero_image_url)
  );
}

/** 
 * Maps the raw database row and overrides it with the AI's editorial tokens 
 * if they exist. This instantly upgrades legacy "slop" into editorial truth.
 */
function toMerchant(store: StoreRow, fallbackSlug: string, tokens: BrandTokens | null): StorefrontMerchant {
  const name = clean(store.shop_name) || fallbackSlug;
  const backgroundImage = clean(store.banner_url);
  
  // If the AI has curated this brand, we use its strict outputs.
  // Otherwise, we gracefully fall back to the legacy bio.
  const title = tokens?.hero_kicker || name;
  const subtitle = tokens?.provenance_statement || clean(store.bio);

  return {
    name,
    whatsappNumber: clean(store.phone),
    // Attach the AI tokens so the Matrix can conditionally style colors/fonts
    ...(tokens && { brandTokens: tokens }), 
    hero: {
      title,
      ...(subtitle ? { subtitle } : {}),
      ...(backgroundImage ? { backgroundImage } : {}),
    },
  };
}

function toProduct(row: ProductRow): StorefrontProduct {
  const price = Number(row.price);
  return {
    id: row.id,
    name: clean(row.name),
    kicker: clean(row.kicker) || clean(row.eyebrow) || clean(row.category),
    extraction: clean(row.extraction),
    price: Number.isFinite(price) && price > 0 ? Math.round(price) : 0,
    image: pickImage(row),
    inStock: row.stock_quantity === null || row.stock_quantity === undefined || row.stock_quantity > 0,
    reviewCount: 0,
    rating: 0,
    description: toParagraphs(row.description),
    details: toBullets(row.details),
  };
}

// --- Data access ---

function getSupabase() {
  return createClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!,
  );
}

/**
 * Server-only service-role client. `public.shop_websites` has NO public anon
 * SELECT policy, so the published-website check MUST bypass RLS here; access
 * control is enforced in code (status === 'published' for visitors).
 */
function getAdminSupabase() {
  return createClient(
    process.env.NEXT_PUBLIC_SUPABASE_URL!,
    process.env.SUPABASE_SERVICE_ROLE_KEY!,
    { auth: { persistSession: false, autoRefreshToken: false } },
  );
}

function decodeSlugParam(raw: string): string {
  try {
    return decodeURIComponent(raw);
  } catch {
    return raw;
  }
}

async function fetchStore(rawSlug: string, cleanSlug: string): Promise<StoreRow | null> {
  const supabase = getSupabase();
  const candidates = rawSlug === cleanSlug ? [cleanSlug] : [cleanSlug, rawSlug];
  for (const candidate of candidates) {
    const { data, error } = await selectWithOptionalColumns<StoreRow>(
      STORE_COLUMNS,
      STORE_OPTIONAL_COLUMNS,
      (columns) => supabase.from('shops').select(columns).eq('shop_slug', candidate).maybeSingle(),
      'switchboard/shops',
    );
    if (error) throw new Error(`[switchboard] shop read failed: ${error.message}`);
    if (data) return data as StoreRow;
  }
  return null;
}

async function fetchProducts(storeId: string): Promise<ProductRow[]> {
  const { data, error } = await selectWithOptionalColumns<ProductRow[]>(
    PRODUCT_BASE_COLUMNS,
    LUXURY_COLUMNS,
    (columns) =>
      getSupabase()
        .from('products')
        .select(columns)
        .or(`shop_id.eq.${storeId},user_id.eq.${storeId}`)
        .order('created_at', { ascending: false }),
    'switchboard',
  );
  if (error) throw new Error(`[switchboard] products read failed: ${error.message}`);
  return data ?? [];
}

type WebsiteRow = {
  status: string | null;
  config: unknown;
  brand_tokens: unknown;
};

/**
 * Retrieves the shop's website row: publish status + WebsiteConfig (the
 * /site/[slug] bridge decision) and the strict JSON brand_tokens minted by
 * the AI Creative Director. Service-role read — see getAdminSupabase.
 */
async function fetchWebsiteRow(storeId: string): Promise<WebsiteRow | null> {
  const { data, error } = await getAdminSupabase()
    .from('shop_websites')
    .select('status, config, brand_tokens')
    .eq('shop_id', storeId)
    .maybeSingle();

  if (error || !data) return null;
  return data as WebsiteRow;
}

// --- Page ---

export default async function SwitchboardPage({
  params,
  searchParams,
}: {
  params: Promise<{ slug: string }>;
  searchParams?: Promise<{ classic?: string }>;
}) {
  const { slug } = await params;
  const rawSlug = decodeSlugParam(slug);
  const cleanSlug = slugify(rawSlug);
  if (!cleanSlug) notFound();

  // 1. Parallel data fetching for maximum edge performance
  const store = await fetchStore(rawSlug, cleanSlug);
  if (!store) notFound();

  const [rows, websiteRow] = await Promise.all([
    fetchProducts(store.id),
    fetchWebsiteRow(store.id),
  ]);

  // 1b. THE /site/[slug] BRIDGE — a published, schema-valid AI website is the
  // storefront of record. Only `?classic=1` (or no published site) falls
  // through to the Switchboard matrices below.
  const resolvedSearch = searchParams ? await searchParams : undefined;
  if (
    resolvedSearch?.classic !== '1' &&
    websiteRow?.status === 'published' &&
    WebsiteConfigSchema.safeParse(websiteRow.config).success
  ) {
    redirect(`/site/${cleanSlug}`);
  }

  const brandTokens = (websiteRow?.brand_tokens as BrandTokens | null) ?? null;

  // 2. Data mapping and formatting
  const merchant = toMerchant(store, cleanSlug, brandTokens);
  const products = rows.map(toProduct).filter((product) => product.image);
  const theme = normalizeThemeMatrix(store.theme_matrix);

  // 3. THE MATRIX ROUTER
  switch (theme) {
    case 'banjul-noir':
      return (
        <main className="min-h-screen bg-mall-forest">
          <BanjulNoirStorefront merchant={merchant} products={products} />
        </main>
      );
      
    case 'dakar-minimal':
    default: // <-- Temporarily placed here so all stores render the new layout
      return <DakarMinimalStorefront merchant={merchant} products={products} />;
  }
}